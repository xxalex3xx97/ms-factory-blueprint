// Regenerates the worker source in memory and compares it to the committed js/worker_src.js.
// Run: node tests/worker_bundle_fresh.mjs   Exit 1 on mismatch.
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';
import {buildWorker} from '../tools/worker_bundle.mjs';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fresh = '// GENERATED by tools/worker_bundle.mjs - do not edit\nglobalThis.FB_WORKER_SRC=' + JSON.stringify(buildWorker()) + ';\n';
const cur = fs.readFileSync(path.join(ROOT, 'js', 'worker_src.js'), 'utf8');
const ok = fresh === cur;
console.log((ok ? 'PASS' : 'FAIL') + ' js/worker_src.js matches tools/worker_bundle.mjs output (' + cur.length + ' bytes)' + (ok ? '' : ' - run: node tools/worker_bundle.mjs'));
process.exit(ok ? 0 : 1);
