// node extract/gen_roofless.mjs > js/roofless.js : top-down wall plans from floors.json colliders_raw (z0<2.5 only: drops door lintels + ceiling slab)
import fs from 'fs';
const B = JSON.parse(fs.readFileSync(new URL('./floors.json', import.meta.url))).blocks;
const K = ['BPO_Station_01', 'BPO_Station_2x1', 'BPO_Station_02A', 'BPO_Station_02', 'BPO_ElevatorBlock_03', 'BPO_SolarPanelBlock', 'BPO_SolarPanelBlock_02', 'BPO_SolarPanelBlock_03', 'BPO_StationTurretBlock_01'];
const o = {};
for (const k of K) {
  const b = B[k], solid = b.kind === 'solid_or_nonrect';
  o[k] = {w: Math.round(b.hull.size[0]), h: Math.round(b.hull.size[1]), solid: solid ? 1 : 0,
    r: b.colliders_raw.filter(c => c[0][2] < 2.5).map(c => [c[0][0], c[0][1], c[1][0], c[1][1]].map(v => Math.round(v * 1000) / 1000))};
}
console.log('// generated by extract/gen_roofless.mjs from extract/floors.json (colliders_raw). Plan units: 16 = 1 block cell, origin = block centre, r = [x0,y0,x1,y1]\nconst ROOFLESS=' + JSON.stringify(o) + ';');
