"""Generate js/recnames.js (site recipe key -> game Recipe.Name) from extract/recipe_names.json.

usage: python -I recipe_names.py [../js/recnames.js]
recipe_names.json = {"REC_xxx": {"name": "<exact game Recipe.Name, verbatim>", ...}} dumped from the live game (authoritative; 63 recipes).
Replace that file (e.g. by a newer bp_recipes dump) and rerun. Site key = inputs>output as in js/inspector.js rk(),
built from extract/rea/recipes.json by REC_ id. Recipes missing from the table fall back to a lowercase output name on export
and are flagged ConfigUnverified there.
"""
import sys, os, json
HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    names = json.load(open(os.path.join(HERE, 'recipe_names.json')))
    R = json.load(open(os.path.join(HERE, 'rea', 'recipes.json')))['recipes']
    key = lambda r: '+'.join(x['item'] for x in r['inputs']) + '>' + r['output']['item']
    table = {key(r): names[rid]['name'] for rid, r in R.items() if rid in names}
    missing = sorted(set(R) - set(names))
    print('recipes', len(R), 'named', len(table), 'missing', missing)
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'js', 'recnames.js')
    open(out, 'w', encoding='utf8').write('// generated by extract/recipe_names.py from extract/recipe_names.json (authoritative game Recipe.Name per recipe, verbatim): site recipe key -> name.\nconst RECNAMES=' + json.dumps(table, separators=(',', ':')) + ';\n')
    print('wrote', out)


if __name__ == '__main__': main()
