"""Generate js/connectors.js: the connector pieces each station block class carries (decoded from the cooked EA BPO assets, extract/floors.json `ea.connectors`).
usage: python -I extract/gen_connectors.py
Per class: [connector class, local grid X, Y (4 grid units per block cell, origin = block centre), height, rotation]. Used by connGen() to write the doorway pieces the game's Designer keeps in a design."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
blocks = json.load(open(os.path.join(root, 'extract', 'floors.json'), encoding='utf8'))['blocks']
out = {}
for k in sorted(blocks):
    cs = (blocks[k].get('ea') or {}).get('connectors')
    if cs:
        out[k] = [[c['class'], c['grid'][0], c['grid'][1], c['height'], c['rot']] for c in cs]
body = json.dumps(out, separators=(',', ':'), sort_keys=True)
js = '// generated by extract/gen_connectors.py (python -I). Do not edit by hand.\nconst BLOCK_CONN=' + body + ';\n'
open(os.path.join(root, 'js', 'connectors.js'), 'w', encoding='utf8', newline='\n').write(js)
print(len(out), 'classes,', len(js) // 1024, 'KB')
