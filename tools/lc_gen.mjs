// LC S3 offline cell library generator. Runs lcCellGen for every crafted node of the 4 trees, mk 0..2, K=1..max(tileM,6); writes js/lc_cells.js.
// Output: const LC_CELLS={"<rec>|<K>|<mk>":{w,h,ins,out,nb,sizes,items}} (ok cells only, one entry per line, sorted keys).
// Item array field order is documented in the header of js/lc_cells.js.
// Run:  node tools/lc_gen.mjs     Exit code 1 on page error or write failure.
import {createRequire} from 'module';
import fs from 'fs';
import path from 'path';
import {fileURLToPath, pathToFileURL} from 'url';

const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PW || 'C:/Users/SFidelis/AppData/Roaming/npm/node_modules/omniroute/node_modules/playwright-core');
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const br = await chromium.launch({executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true});
const pg = await (await br.newContext()).newPage();
const errs = [];
pg.on('pageerror', e => errs.push(e.message));
await pg.goto(pathToFileURL(ROOT + '/index.html').href);
await pg.waitForFunction(() => window.__fb && typeof plan === 'function' && typeof pfFactTree === 'function' && typeof lcCellGen === 'function');

const cases = [{name: 'Basic Circuits', rate: 10}, {name: 'Advanced Circuits', rate: 50}, {name: 'Magnetic Coils', rate: 30}, {name: 'Basic Motor', rate: 60}];
const G = await pg.evaluate(cases => {
  const cells = {}, dups = [], missing = [], skipped = [], recs = new Set();
  for (const c of cases) {
    const it = [...plnBy(false).keys()].find(i => plnNm(i) === c.name);
    if (it === undefined) { skipped.push(c.name + ': item not found'); continue }
    for (let mk = 0; mk <= 2; mk++) {
      const P = plan(it, c.rate, mk, {sp: null, bal: null}, PLN_PICK, {proto: false, enr: false});
      const Z = pfFactTree(P, it, mk);
      if (Z.ok === false) { skipped.push(c.name + ' mk' + mk + ': ' + Z.why); continue }
      for (const n of Z.nodes) {
        if (!n.cls) continue;
        recs.add(n.rec);
        for (let K = 1; K <= Math.max(n.tileM, 6); K++) {
          const key = n.rec + '|' + K + '|' + mk;
          const r = lcCellGen(n.cls, n.k, n.flows, K, mk);
          if (r.ok === false) { if (K <= 3) missing.push(key + ' ' + r.why); continue }
          const e = {w: r.w, h: r.h, ins: r.ins, out: r.out, nb: r.nb, sizes: r.sizes, items: r.items};
          if (cells[key]) { if (JSON.stringify(cells[key]) !== JSON.stringify(e)) dups.push(key); continue }
          cells[key] = e;
        }
      }
    }
  }
  return {cells, dups, missing, skipped, recs: [...recs]};
}, cases);

// Item = [cls,x,y,rot] + optional 5th element: object of the remaining fields in original key order (ct, off, ...). Checked: every item starts with cls,x,y,rot.
let badOrder = 0, withExtra = 0;
const lines = [];
for (const key of Object.keys(G.cells).sort()) {
  const e = G.cells[key];
  const items = e.items.map(b => {
    const ks = Object.keys(b);
    if (ks.slice(0, 4).join() !== 'cls,x,y,rot') badOrder++;
    const a = [b.cls, b.x, b.y, b.rot];
    const rest = {};
    for (const k of ks.slice(4)) rest[k] = b[k];
    if (ks.length > 4) { a.push(rest); withExtra++ }
    return a;
  });
  const body = {w: e.w, h: e.h, ins: e.ins, out: e.out, nb: e.nb, sizes: e.sizes, items};
  lines.push(JSON.stringify(key) + ':' + JSON.stringify(body));
}
const extraKeys = new Set();
for (const e of Object.values(G.cells)) for (const b of e.items) for (const k of Object.keys(b)) if (!['cls','x','y','rot'].includes(k)) extraKeys.add(k);
const head = [
  '// LC S3 cell library (generated by tools/lc_gen.mjs, do not edit by hand). Run: node tools/lc_gen.mjs',
  '// Key "<rec>|<K>|<mk>" (rec = cls|k|flow item ids). Value {w,h,ins:[{item,x}],out:{x},nb,sizes,items}.',
  '// item = [cls,x,y,rot] or [cls,x,y,rot,extra] where extra = object of the remaining item fields (' + [...extraKeys].join(',') + ') in original key order; absent fields omitted.',
  '// Items are relative to the cell origin (0,0). Decode in lcCell: rebuild object in this key order, add ox/oy to x/y.',
];
const file = head.join('\n') + '\nconst LC_CELLS={\n' + lines.join(',\n') + '\n};\n';
fs.writeFileSync(path.join(ROOT, 'js', 'lc_cells.js'), file);

console.log('entries ' + lines.length + ' | extra fields ' + [...extraKeys].join(',') + ' | items with extra ' + withExtra + ' | bad key order ' + badOrder);
console.log('recs ' + G.recs.length + ' | dup key mismatches ' + G.dups.length + ' | missing K1..3 ' + G.missing.length);
for (const m of G.missing) console.log('  MISSING ' + m);
for (const s of G.skipped) console.log('  SKIP ' + s);
console.log('size ' + fs.statSync(path.join(ROOT, 'js', 'lc_cells.js')).size + ' bytes');
await br.close();
if (errs.length) { console.log('page errors: ' + errs.join(' | ')); process.exit(1) }
