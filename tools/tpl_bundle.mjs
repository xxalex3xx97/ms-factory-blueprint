// Generates js/tpl/bundle.js (CMP F1): each template in its own IIFE so top-level const/var names do not collide.
// Run: node tools/tpl_bundle.mjs   (exports buildBundle() for tests/tpl_bundle_fresh.mjs)
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TPL_IDS = ['refinery_1in','assembler_1in','assembler_2in','assembler_3in','enrichment_1in','enrichment_2_3in','advassembler_1_2in','advassembler_4in','growth_2_3_4in','special_machines'];
export function buildBundle() {
  let out = '// GENERATED by tools/tpl_bundle.mjs - do not edit. Load after js/tpl/iface.js. Each template is an IIFE; TPLM.<id> = {build,max}.\nconst TPLM={};\n';
  for (const id of TPL_IDS) {
    const src = fs.readFileSync(path.join(ROOT, 'js', 'tpl', id + '.js'), 'utf8').replace(/\r\n/g, '\n');
    out += `TPLM.${id}=(()=>{\n${src}\n;return {build:tplBuild,max:tplMax};})();\n`;
  }
  return out;
}
if (path.resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(ROOT, 'js', 'tpl', 'bundle.js'), buildBundle());
  console.log('wrote js/tpl/bundle.js');
}
